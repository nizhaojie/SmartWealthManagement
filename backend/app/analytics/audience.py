"""查询链路的使用者口径：同一条链路服务员工与客户两种使用者（ADR-0025）。

口径不是身份。身份是执行连接上的会话变量（``app.db.analytics_account``），决定
「查得到哪些行」；口径是**说给谁听**，决定生成查询与解读结果时的提示词与模板。
两者必须成对：客户身份配员工口径的提示词，等于让模型按内部视角解释客户自己的
数据，甚至排出「哪个产品更好」——那是投顾助手的产物，不属于智能客服（ADR-0005）。

取值是稳定标识，不是给人读的文案；两处提示词表（``llm``、``interpretation``）
按它取自己那一份。收成枚举而不是裸字符串：口径要一路传到生成与解读两处，类型
让「传了个不存在的口径」在检查期就暴露，而不是等到取提示词时的 KeyError。
"""

from enum import Enum


class Audience(str, Enum):
    EMPLOYEE = "employee"
    CUSTOMER = "customer"
